# IDENTITY VALIDATOR
# =============================================================================


class IdentityValidator:
    """
    Validates semantic identity assignments.
    
    Ensures identity uniqueness and consistency across the knowledge system.
    """
    
    def __init__(
        self,
        require_namespace: bool = False,
        min_length: int = 8,
        max_length: int = 256,
    ):
        """
        Initialize the validator.
        
        Args:
            require_namespace: Whether identities must include namespace
            min_length: Minimum identity string length
            max_length: Maximum identity string length
        """
        self._require_namespace = require_namespace
        self._min_length = min_length
        self._max_length = max_length
    
    def validate(self, identity: SemanticIdentity) -> Tuple[bool, List[str]]:
        """
        Validate a semantic identity.
        
        Args:
            identity: Identity to validate
            
        Returns:
            (is_valid, list_of_issues)
        """
        issues = []
        
        # Rule 1: Must have non-empty identity
        if not identity.identity or len(identity.identity) == 0:
            issues.append("Empty identity")
        
        # Rule 2: Length constraints
        if len(identity.identity) < self._min_length:
            issues.append(f"Identity too short (min: {self._min_length})")
        
        if len(identity.identity) > self._max_length:
            issues.append(f"Identity too long (max: {self._max_length})")
        
        # Rule 3: Namespace requirement
        if self._require_namespace and not identity.namespace:
            issues.append("Missing required namespace")
        
        # Rule 4: Source must be known
        if identity.source == IdentitySource.UNKNOWN:
            issues.append("Unknown identity source")
        
        return len(issues) == 0, issues


