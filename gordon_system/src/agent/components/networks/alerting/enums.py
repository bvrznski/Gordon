class AlertingStateTransition(Enum):
    """
    Bounded state transition type for a signal.
    
    Describes how the internal state evolved during assessment.
    Used for explainability and debugging, not behavioral control.
    """
    
    NEW_SIGNAL = "new_signal"  # First observation of this signal
    BASELINE_UPDATE = "baseline_update"  # Updated baseline statistics
    HABITUATION_CHANGE = "habituation_change"  # Habituation level changed
    REFRATORY_EXPIRED = "refractory_expired"  # Refractory period ended
    INTENSITY_SHIFT = "intensity_shift"  # Significant intensity change detected
    NOVELTY_DETECTED = "novelty_detected"  # Signal differs from baseline
    
    @property
    def is_state_change(self) -> bool:
        """Return True if this transition represents a state mutation."""
        return self != AlertingStateTransition.NEW_SIGNAL