# Reflection Outcome Models
# ==========================

"""
Immutable models for reflection outcomes, proposals, and continuation.

ARCHITECTURAL PRINCIPLES:
    - Outcomes are terminal results, not runtime commands
    - Proposals remain advisory (never automatically applied)
    - Continuation recommendations do NOT schedule execution
    - No runtime dependencies
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Tuple, Optional


# =============================================================================
# PROPOSAL KINDS (re-exported for convenience)
# =============================================================================

