# COMPLETENESS ASSESSMENT
# =============================================================================

class ReflectionCompleteness:
    """
    Structured completeness assessment for reflection.
    
    Completeness measures whether all required elements are present,
    not the quality of what is present.
    """
    
    COMPLETE = "complete"
    """All required elements present and sufficient."""
    
    SUFFICIENT = "sufficient"
    """Sufficient elements present for meaningful results."""
    
    PARTIAL = "partial"
    """Some elements present but incomplete."""
    
    INSUFFICIENT = "insufficient"
    """Not enough elements for meaningful reflection."""
    
    INVALID = "invalid"
    """Reflection context is invalid."""
    
    @classmethod
    def all_statuses(cls) -> Tuple[str, ...]:
        """Return all completeness statuses."""
        return (
            cls.COMPLETE,
            cls.SUFFICIENT,
            cls.PARTIAL,
            cls.INSUFFICIENT,
            cls.INVALID,
        )
    
    @classmethod
    def is_acceptable(cls, status: str) -> bool:
        """Check if status allows reflection to proceed."""
        return status in {cls.COMPLETE, cls.SUFFICIENT}
    
    @classmethod
    def is_terminal(cls, status: str) -> bool:
        """Check if status represents a terminal condition."""
        return status in {cls.INVALID}


@dataclass(frozen=True, slots=True)
class ReflectionCompletenessRecord:
    """
    Detailed completeness assessment for reflection.
    
    This provides granular information about what's present and what's missing.
    
    PROPERTIES:
        • overall_status: High-level completeness (ReflectionCompleteness.*)
        • required_count: How many elements are required
        • supplied_count: How many elements were found
        • missing_required: Which required elements are absent
        • optional_supplied: Optional elements that were present
        
    BOUNDEDNESS:
        All lists must be bounded.
    """
    
    overall_status: str  # ReflectionCompleteness.*
    """High-level completeness assessment."""
    
    required_count: int = 0
    """Number of required context elements."""
    
    supplied_count: int = 0
    """Number of required elements that were supplied."""
    
    missing_required: Tuple[str, ...] = field(default_factory=tuple)
    """Required elements that are missing."""
    
    optional_supplied: int = 0
    """Optional elements that were provided."""
    
    @classmethod
    def complete(cls) -> ReflectionCompletenessRecord:
        """Create a complete record."""
        return cls(
            overall_status=ReflectionCompleteness.COMPLETE,
            required_count=0,
            supplied_count=0,
        )
    
    @classmethod
    def insufficient(cls, missing: Tuple[str, ...]) -> ReflectionCompletenessRecord:
        """Create an insufficient record."""
        return cls(
            overall_status=ReflectionCompleteness.INSUFFICIENT,
            required_count=len(missing),
            supplied_count=0,
            missing_required=missing,
        )
    
    @classmethod
    def partial(cls, supplied: int, total: int) -> ReflectionCompletenessRecord:
        """Create a partial record."""
        return cls(
            overall_status=ReflectionCompleteness.PARTIAL,
            required_count=total,
            supplied_count=supplied,
            missing_required=tuple(f"element_{i}" for i in range(supplied, total)),
        )