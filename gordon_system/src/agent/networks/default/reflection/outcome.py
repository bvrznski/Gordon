# CONFIDENCE ASSESSMENT
# =============================================================================

@dataclass(frozen=True, slots=True)
class ReflectionConfidence:
    """
    Structured confidence assessment for reflection outcomes.
    
    Confidence measures evidential quality, not truth. High confidence
    means strong supporting evidence; low confidence means weak or
    conflicting evidence.
    
    PROPERTIES:
        • overall_confidence: Overall confidence level (0.0 to 1.0)
        • context_confidence: Confidence in the input context
        • evidence_quality: Quality of collected evidence
        • agreement_count: Number of supporting evidence items
        • contradiction_count: Number of conflicting evidence items
        
    NOT RANKED AS:
        - Importance
        - Novelty  
        - Utility
        - Truth value
    """
    
    overall_confidence: float  # 0.0 to 1.0
    """Overall confidence level."""
    
    context_confidence: float = 0.5
    """Confidence in the input context."""
    
    evidence_quality: float = 0.5
    """Quality of collected evidence (0.0 to 1.0)."""
    
    agreement_count: int = 0
    """Number of supporting evidence items."""
    
    contradiction_count: int = 0
    """Number of conflicting evidence items."""
    
    stale_inputs: Tuple[str, ...] = field(default_factory=tuple)
    """Input sources that may be outdated."""
    
    alternative_explanations: Tuple[str, ...] = field(default_factory=tuple)
    """Alternative interpretations considered."""
    
    @classmethod
    def high(cls) -> ReflectionConfidence:
        """Create a high-confidence assessment."""
        return cls(
            overall_confidence=0.8,
            context_confidence=0.9,
            evidence_quality=0.85,
            agreement_count=3,
            contradiction_count=0,
        )
    
    @classmethod
    def medium(cls) -> ReflectionConfidence:
        """Create a medium-confidence assessment."""
        return cls(
            overall_confidence=0.6,
            context_confidence=0.7,
            evidence_quality=0.65,
            agreement_count=1,
            contradiction_count=1,
        )
    
    @classmethod
    def low(cls) -> ReflectionConfidence:
        """Create a low-confidence assessment."""
        return cls(
            overall_confidence=0.3,
            context_confidence=0.4,
            evidence_quality=0.35,
            agreement_count=0,
            contradiction_count=2,
        )
    
    @classmethod
    def unknown(cls) -> ReflectionConfidence:
        """Create an unknown-confidence assessment."""
        return cls(
            overall_confidence=0.5,
            context_confidence=0.5,
            evidence_quality=0.5,
        )


