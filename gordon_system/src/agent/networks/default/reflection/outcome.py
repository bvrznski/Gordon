# REFLECTION CONTINUATION RECOMMENDATIONS
# =============================================================================

@dataclass(frozen=True, slots=True)
class ReflectionContinuation:
    """
    Advisory continuation recommendation from reflection.
    
    Continuation recommendations are semantic guidance, NOT runtime
    commands. They must be interpreted by a higher-level coordinator.
    
    PROPERTIES:
        • kind: What to do next (ReflectionContinuationKind.*)
        • description: Human-readable explanation
        • proposed_next_steps: Recommended follow-up actions
        
    BOUNDEDNESS:
        Continuation must remain advisory and bounded.
    """
    
    kind: str  # ReflectionContinuationKind.*
    """The recommended continuation."""
    
    description: str = ""
    """Human-readable explanation."""
    
    proposed_next_steps: Tuple[str, ...] = field(default_factory=tuple)
    """Recommended follow-up actions or episodes."""
    
    @classmethod
    def complete(cls) -> ReflectionContinuation:
        """Create a completion recommendation."""
        return cls(
            kind="complete",
            description="Reflection completed successfully.",
        )
    
    @classmethod
    def continue_with_current_context(cls) -> ReflectionContinuation:
        """Continue with current context."""
        return cls(
            kind="continue_with_current_context",
            description="Continue processing with current context and plan.",
        )
    
    @classmethod
    def request_context_refresh(cls, reason: str = "") -> ReflectionContinuation:
        """Request a context refresh."""
        return cls(
            kind="request_context_refresh",
            description=f"Context needs refresh: {reason}" if reason else "Refresh context binding.",
        )
    
    @classmethod
    def wait_for_evidence(cls) -> ReflectionContinuation:
        """Wait for additional evidence."""
        return cls(
            kind="wait_for_evidence",
            description="Waiting for additional evidence to become available.",
        )
    
    @classmethod
    def suspend(cls, reason: str = "") -> ReflectionContinuation:
        """Suspend processing."""
        return cls(
            kind="suspend",
            description=f"Suspended: {reason}" if reason else "Processing suspended temporarily.",
        )
    
    @classmethod
    def derive_child_episode(
        cls,
        child_purpose: str,
        child_subject: str,
    ) -> ReflectionContinuation:
        """Derive a child episode."""
        return cls(
            kind="derive_child_episode",
            description=f"Create child episode for: {child_subject}",
            proposed_next_steps=(f"episode:{child_purpose}:{child_subject}",),
        )
    
    @classmethod
    def fail(cls, failure_reason: str) -> ReflectionContinuation:
        """Mark as failed."""
        return cls(
            kind="fail",
            description=f"Reflection failed: {failure_reason}",
        )
    
    @classmethod
    def cancel(cls, cancellation_reason: str) -> ReflectionContinuation:
        """Cancel the reflection."""
        return cls(
            kind="cancel",
            description=f"Reflection cancelled: {cancellation_reason}",
        )


